/**
 * `supabase/content/emotion-wheel.yml` → `apps/web/src/content/emotionWheel.ts`
 *
 * A GENERATOR, because the repo has no YAML parser and this screen did not
 * justify adding one. The wheel is 128 words that change when the source
 * image changes, which is approximately never — so the app reads a typed
 * module and this script is how that module is made honest again.
 *
 * It is deliberately a parser for THIS file's shape, not for YAML. The file is
 * hand-written in one regular form (three nested levels, flow maps only at the
 * leaves), and it asserts the ring sizes the source states — 8, 40, 80 — so a
 * transcription error in the yml fails here rather than in the browser.
 *
 * Run: node apps/web/scripts/emotion-wheel.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'supabase/content/emotion-wheel.yml';
const OUT = 'apps/web/src/content/emotionWheel.ts';

const lines = readFileSync(SRC, 'utf8').split('\n');

/** The leaves are flow maps: `- { i: 0, deg: [0, 3.75], en: Powerful, de: Kraftvoll }` */
function flow(line) {
  const i = /[{,]\s*i:\s*(\d+)/.exec(line);
  const en = /\ben:\s*([^,}]+)/.exec(line);
  const de = /\bde:\s*([^,}]+)/.exec(line);
  if (!i || !en || !de) throw new Error(`leaf missing a field: ${line}`);
  return { i: Number(i[1]), en: en[1].trim(), de: de[1].trim() };
}

const scalar = (line) => line.slice(line.indexOf(':') + 1).trim();

const emotions = [];
let emotion = null;
let detailed = null;
let inEmotions = false;

for (const line of lines) {
  if (/^emotions:/.test(line)) {
    inEmotions = true;
    continue;
  }
  if (!inEmotions || !line.trim() || line.trim().startsWith('#')) continue;

  const indent = line.length - line.trimStart().length;
  const body = line.trim();

  if (indent === 2 && body.startsWith('- id:')) {
    emotion = { id: scalar(body), i: 0, en: '', de: '', detailed: [] };
    emotions.push(emotion);
    detailed = null;
  } else if (indent === 6 && body.startsWith('- id:')) {
    detailed = { id: scalar(body), i: 0, en: '', de: '', specific: [] };
    emotion.detailed.push(detailed);
  } else if (indent === 10 && body.startsWith('- {')) {
    detailed.specific.push(flow(body));
  } else if (indent === 4 || indent === 8) {
    const target = indent === 4 ? emotion : detailed;
    if (body.startsWith('i:')) target.i = Number(scalar(body));
    else if (body.startsWith('en:')) target.en = scalar(body);
    else if (body.startsWith('de:')) target.de = scalar(body);
  }
}

const detailedCount = emotions.reduce((n, e) => n + e.detailed.length, 0);
const specificCount = emotions.reduce(
  (n, e) => n + e.detailed.reduce((m, d) => m + d.specific.length, 0),
  0,
);

/** The source states its own ring sizes. Hold it to them. */
const expected = { emotions: 8, detailed: 40, specific: 80 };
const actual = { emotions: emotions.length, detailed: detailedCount, specific: specificCount };
for (const ring of Object.keys(expected)) {
  if (actual[ring] !== expected[ring]) {
    throw new Error(`${SRC} says ${ring} is ${expected[ring]}, parsed ${actual[ring]}`);
  }
}
for (const e of emotions) {
  for (const d of e.detailed) {
    if (d.specific.length !== 2) {
      throw new Error(`${e.id} › ${d.id} holds ${d.specific.length} specifics, not 2`);
    }
  }
}

const header = `/**
 * The emotion wheel, as the app reads it — 8 emotions, 40 detailed, 80 specific.
 *
 * GENERATED by apps/web/scripts/emotion-wheel.mjs from
 * supabase/content/emotion-wheel.yml. Do not edit by hand: edit the yml and
 * run the script, which also re-checks the ring sizes.
 *
 * Each word carries its \`i\` — its 0-based index clockwise from twelve
 * o'clock within its own ring — because the yml is emphatic that a word is not
 * a key: Powerful appears twice and Delighted appears twice, so \`i\` is the
 * identity and the label is not. The \`deg\` spans are NOT carried; nothing
 * draws a circle yet, and a column of unused numbers would read as a promise
 * this file does not keep.
 *
 * Both languages sit on every node because these are CONTENT words, not
 * chrome — they belong beside \`supabase/content\`, not in \`i18n/en.ts\`, and
 * the screen picks a side with the active locale.
 */
`;

const body = `
export interface WheelWord {
  /** 0-based index clockwise from twelve o'clock, within its own ring. */
  readonly i: number;
  readonly en: string;
  readonly de: string;
}

export interface WheelDetailed extends WheelWord {
  readonly id: string;
  readonly specific: readonly WheelWord[];
}

export interface WheelEmotion extends WheelWord {
  readonly id: string;
  readonly detailed: readonly WheelDetailed[];
}

export const EMOTION_WHEEL: readonly WheelEmotion[] = ${JSON.stringify(emotions, null, 2)};
`;

writeFileSync(OUT, header + body);
console.log(
  `${OUT}: ${actual.emotions} emotions, ${actual.detailed} detailed, ${actual.specific} specific`,
);
